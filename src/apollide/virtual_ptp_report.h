/*
 * Apollide virtual precision touchpad — HID reports shared by the driver (Apollide/ptp-driver) and the host (src/apollide/virtual_ptp.cpp).
 *
 * Windows only turns on its precision-touchpad engine (two-finger scrolling with inertia,
 * gestures) for a touchpad HID device; software cannot inject touchpad contacts directly.
 * This UMDF HID minidriver presents such a device. Apollide (or the test tool) writes contact
 * frames into the vendor collection as a feature report, and the driver hands them to Windows
 * as touchpad input reports.
 *
 * Collections:
 *   1. Digitizer / Touch Pad   — input report 1 (contacts), feature 2 (capabilities), feature 3 (PTPHQA blob)
 *   2. Digitizer / Configuration — feature 4 (input mode), feature 5 (surface/button switches)
 *   3. Generic Desktop / Mouse — input report 7 (never sent; Windows expects it for legacy mode)
 *   4. Vendor 0xFF00 / 0x01    — feature 6 (contact frame to inject)
 */
#pragma once

#include <stdint.h>

#define PTP_VENDOR_ID 0x1209
#define PTP_PRODUCT_ID 0xA9D1
#define PTP_DEVICE_VERSION 0x0001

#define PTP_REPORT_TOUCHPAD 0x01
#define PTP_REPORT_CAPS 0x02
#define PTP_REPORT_PTPHQA 0x03
#define PTP_REPORT_INPUT_MODE 0x04
#define PTP_REPORT_FUNCTION_SWITCH 0x05
#define PTP_REPORT_INJECT 0x06
#define PTP_REPORT_MOUSE 0x07

#define PTP_MAX_CONTACTS 5
#define PTP_LOGICAL_MAX_X 4095
#define PTP_LOGICAL_MAX_Y 2730  /* 3:2 like the Surface touchpad */

/* Finger flags: bit0 confidence, bit1 tip switch, bits2-4 contact id */
#define PTP_FINGER_CONFIDENCE 0x01
#define PTP_FINGER_TIP 0x02
#define PTP_FINGER_ID(id) ((uint8_t) (((id) & 0x07) << 2))

#pragma pack(push, 1)
typedef struct {
  uint8_t flags;
  uint16_t x;
  uint16_t y;
} ptp_finger_t;

/* Input report 1, and the payload of feature report 6 (same layout) */
typedef struct {
  uint8_t report_id;
  ptp_finger_t fingers[PTP_MAX_CONTACTS];
  uint16_t scan_time;  /* 100 µs units, wraps */
  uint8_t contact_count;
  uint8_t buttons;  /* bit0 = pad click */
} ptp_touchpad_report_t;
#pragma pack(pop)

#define PTP_TOUCHPAD_REPORT_SIZE ((int) sizeof(ptp_touchpad_report_t))
#define PTP_PTPHQA_SIZE 256

/* clang-format off */
